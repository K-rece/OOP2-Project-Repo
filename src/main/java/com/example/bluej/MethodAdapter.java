package com.example.bluej;

import java.io.File;
import java.util.ArrayList;
import java.util.List;
import com.example.MethodTracker;
import com.example.TelemetryCollector;
import com.example.TelemetryEventFactory;
import bluej.extensions2.BClass;
import bluej.extensions2.BMethod;
import bluej.extensions2.BPackage;
import bluej.extensions2.BProject;
import bluej.extensions2.BlueJ;
import bluej.extensions2.event.CompileEvent;
import bluej.extensions2.event.CompileListener;


/**
 * Adapter: after each successful compile the student starts, asks BlueJ for the compiled classes'
 * methods and publishes a {@link com.example.EventType#METHOD_ADDED} event for each new one.
 * Working out which methods are new is delegated to {@link MethodTracker}.
 */
public class MethodAdapter implements CompileListener {
    
  /** BlueJ's extension interface, used to find the compiled classes. */
  private final BlueJ blueJ;
  /** This is where the converted events are published. */
  private final TelemetryCollector collector;
  /** Creates the plugin's events. */
  private final TelemetryEventFactory factory;
  /** Remembers each class's methods between compiles. */
  private final MethodTracker tracker;

  /**
   * Creates the adapter.
   *
   * @param blueJ BlueJ's extension interface
   * @param collector where METHOD_ADDED events are published
   * @param factory creates the events
   * @param tracker remembers each class's methods between compiles
   */
  public MethodAdapter(BlueJ blueJ, TelemetryCollector collector, TelemetryEventFactory factory,
      MethodTracker tracker) {
    this.blueJ = blueJ;
    this.collector = collector;
    this.factory = factory;
    this.tracker = tracker;
  }

  /**
   * Called by BlueJ when a compile succeeds. For each compiled file, publishes a METHOD_ADDED
   * event for every method not seen at the previous compile. BlueJ's background checks are
   * ignored.
   *
   * @param event BlueJ's description of the compile
   */
  @Override
  public void compileSucceeded(CompileEvent event) {
    if (!event.isUserGeneratedCompilation()) {
      return; 
    }
    for (File file : event.getFiles()) {
      try {
        publishNewMethods(file);
      } catch (Exception e) {
        System.out.println("Telemetry: method scan error: " + e.getMessage());
      }
    }
  }

  /**
   * Finds the class for a compiled file and publishes its new methods. Methods generated by the
   * compiler (with {@code $} in their name) are skipped.
   *
   * @param javaFile the compiled source file
   * @throws Exception if BlueJ cannot provide the class or its methods
   */
  private void publishNewMethods(File javaFile) throws Exception {
    BClass bClass = findClass(javaFile);
    if (bClass == null) {
      return;
    }
    List<String> signatures = new ArrayList<>();
    for (BMethod method : bClass.getDeclaredMethods()) {
      if (!method.getName().contains("$")) { 
        signatures.add(signature(method));
      }
    }
    String className = bClass.getName();
    for (String added : tracker.findNewMethods(className, signatures)) {
      collector.publish(factory.methodAdded(className, added));
    }
  }

  /**
   * Finds the BlueJ class for a compiled source file, e.g. {@code .../Shapes/Dog.java} gives
   * {@code Dog}. A class in the same folder as the file is preferred over one with the same name
   * elsewhere.
   *
   * @param javaFile the compiled source file
   * @return the matching class, or null if none is found
   * @throws Exception if BlueJ cannot list the open projects or packages
   */
  private BClass findClass(File javaFile) throws Exception {
    String fileName = javaFile.getName();
    if (!fileName.endsWith(".java")) {
      return null;
    }
    String className = fileName.substring(0, fileName.length() - ".java".length());
    BClass sameName = null;
    for (BProject project : blueJ.getOpenProjects()) {
      for (BPackage bPackage : project.getPackages()) {
        BClass candidate = bPackage.getBClass(className);
        if (candidate == null) {
          continue;
        }
        if (bPackage.getDir().equals(javaFile.getParentFile())) {
          return candidate; 
        }
        sameName = candidate;
      }
    }
    return sameName;
  }


  /**
   * Builds a signature for a method.
   *
   * @param method the method
   * @return the method's name and parameter types
   */
  private String signature(BMethod method) {
    StringBuilder sb = new StringBuilder(method.getName()).append("(");
    Object[] parameters = method.getParameterTypes();
    for (int i = 0; i < parameters.length; i++) {
      if (i > 0) {
        sb.append(", ");
      }
      Object p = parameters[i];
      sb.append(p instanceof Class ? ((Class<?>) p).getSimpleName() : String.valueOf(p));
    }
    return sb.append(")").toString();
  }

  /**
   * Not used: other compile events are handled by {@link CompileAdapter}.
   *
   * @param event BlueJ's description of the compile
   */
  @Override
  public void compileStarted(CompileEvent event) {
  }

  /**
   * Not used: other compile events are handled by {@link CompileAdapter}.
   *
   * @param event BlueJ's description of the compile
   */
  @Override
  public void compileError(CompileEvent event) {
  }

  /**
   * Not used: other compile events are handled by {@link CompileAdapter}.
   *
   * @param event BlueJ's description of the compile
   */
  @Override
  public void compileWarning(CompileEvent event) {
  }

  /**
   * Not used: other compile events are handled by {@link CompileAdapter}.
   *
   * @param event BlueJ's description of the compile
   */
  @Override
  public void compileFailed(CompileEvent event) {
  }
}